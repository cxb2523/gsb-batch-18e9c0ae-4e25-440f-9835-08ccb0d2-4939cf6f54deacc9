import type { OutlineEntry } from '@prismbox/core';

const BADGE: Record<OutlineEntry['edit'], { label: string; title: string } | null> = {
  editable: null,
  partial: { label: 'partial', title: 'Some props are literals and editable; others are expressions and read-only' },
  'read-only': { label: 'locked', title: 'Read-only' },
};

function badgeFor(e: OutlineEntry): { label: string; title: string; cls: string } | null {
  const n = e.node;
  if (n.status === 'opaque') return { label: 'opaque', title: 'Contents are not understood, so this is never rewritten', cls: 'opaque' };
  if (n.status === 'instance') return { label: 'map', title: 'Generated by .map(): selectable, never rewritten', cls: 'locked' };
  const b = BADGE[e.edit];
  return b ? { ...b, cls: e.edit === 'partial' ? 'partial' : 'locked' } : null;
}

const GLYPH: Record<string, string> = { canvas: '▣', drei: '◇' };
function glyph(e: OutlineEntry): string {
  const t = e.node.tag;
  if (GLYPH[e.node.kind]) return GLYPH[e.node.kind] as string;
  if (/Light$/.test(t)) return '☼';
  if (/Geometry$/.test(t)) return '△';
  if (/Material$/.test(t)) return '●';
  if (t === 'group') return '▢';
  return '◼';
}

/** Nodes written inside wrapper components (Spin, MouseFollow, ...) are listed apart from the scene's own tree. */
function partition(entries: OutlineEntry[]): { scene: OutlineEntry[]; behaviors: OutlineEntry[] } {
  const canvas = entries.find((e) => e.node.kind === 'canvas');
  const root = canvas ? canvas.node.pathId.split(':')[0] : null;
  if (!root) return { scene: entries, behaviors: [] };
  const scene: OutlineEntry[] = [];
  const behaviors: OutlineEntry[] = [];
  for (const e of entries) (e.node.pathId.split(':')[0] === root ? scene : behaviors).push(e);
  return { scene, behaviors };
}

function Row({ e, base, selected, onSelect }: { e: OutlineEntry; base: number; selected: boolean; onSelect: (id: string) => void }) {
  const b = badgeFor(e);
  return (
    <button
      type="button"
      role="treeitem"
      aria-selected={selected}
      className={`tree-row${selected ? ' selected' : ''}${e.edit === 'read-only' ? ' dimmed' : ''}`}
      style={{ paddingLeft: 10 + (e.depth - base) * 14 }}
      onClick={() => onSelect(e.node.id)}
      title={e.node.reasons.join('; ') || `<${e.node.tag}> at line ${e.node.line}`}
    >
      <span className="glyph" aria-hidden>{glyph(e)}</span>
      <span className="tree-name">{e.node.name ?? e.node.tag}</span>
      {e.node.name && <span className="tree-tag">{e.node.tag}</span>}
      {b && <span className={`badge ${b.cls}`} title={b.title}>{b.label}</span>}
    </button>
  );
}

export function Tree({ entries, selectedId, onSelect }: { entries: OutlineEntry[]; selectedId: string | null; onSelect: (id: string) => void }) {
  const editable = entries.filter((e) => e.edit === 'editable').length;
  const { scene, behaviors } = partition(entries);
  const base = (list: OutlineEntry[]) => (list.length ? Math.min(...list.map((x) => x.depth)) : 0);
  return (
    <aside className="panel tree">
      <div className="panel-head">
        <span>Scene</span>
        <span className="count" title="Nodes that are fully editable">{editable}/{entries.length} editable</span>
      </div>
      <div className="tree-list" role="tree">
        {scene.map((e) => <Row key={`${e.node.pathId}:${e.node.line}:${e.node.col}`} e={e} base={base(scene)} selected={e.node.id === selectedId} onSelect={onSelect} />)}
        {behaviors.length > 0 && <div className="tree-group" title="Nodes written inside wrapper components such as Spin or MouseFollow">Behaviors</div>}
        {behaviors.map((e) => <Row key={`${e.node.pathId}:${e.node.line}:${e.node.col}`} e={e} base={base(behaviors)} selected={e.node.id === selectedId} onSelect={onSelect} />)}
      </div>
    </aside>
  );
}
